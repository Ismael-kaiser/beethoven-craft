/// El efecto «Mezcla de color» con los valores del filtro `i`.
pub fn efecto(id: u64, i: usize) -> Option<FxVideo> {
    let x = FILTROS.get(i)?;
    let mut e = crate::vpropios::nuevo(id, crate::vpropios::buscar("bc:color")?);
    for (k, v) in ["exp", "con", "sat", "temp", "tinte", "giro", "deslavar", "vin", "grano"].into_iter().zip(x.base) {
        e.p.get_mut(k)?.v = Valor::Num(v);
    }
    for (k, r) in ["sombras", "medios", "luces"].into_iter().zip(x.ruedas) {
        e.p.get_mut(k)?.v = Valor::Punto([r[0], r[1]]);
        e.p.get_mut(&format!("{k}_l"))?.v = Valor::Num(r[2]);
    }
    Some(e)
}
